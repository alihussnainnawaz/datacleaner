@router.get("/{data_type}/{ip_name}/{file_id}/records",
            summary="Fetch full records sharing this CNIC, within this IP's own cleaned file (beneficiary / banks / financials)")
@router.get("/{data_type}/{file_id}/records",
            summary="Fetch full records sharing this CNIC, within this file's own cleaned data (certificates)")
async def get_records_by_cnic(
    data_type: str,
    file_id: str,
    ip_name: Optional[str] = None,
    cnic: str = Query(..., description="CNIC to look up — dashes/spaces are fine, normalized automatically"),
):
    """Given a CNIC, find and return the full record for every row within
    this specific IP's own _cleaned.parquet whose CNIC (after
    normalization) matches it — e.g. a CNIC that repeats 3 times within
    this IP returns all 3 full rows.

    Scoped to a single IP, same URL shape as /page and /duplicates — this
    does NOT search other IPs. Use /{data_type}/cnic/records?cnic=... (no
    ip_name/file_id) if you want the cross-IP lookup instead.

    Reads from _cleaned.parquet: every field is a plain column (including
    the CNIC column itself, e.g. "DA_CNIC") with no JSON-encoded values to
    decode, so a match here is a direct row dump — no json.loads() needed.

    The CNIC is normalized the same way as everywhere else (whitespace/
    dashes stripped, float ".0" artifacts removed), so "4530-358-104832"
    and "4530358104832" both resolve to the same lookup.
    """
    target = _normalize_cnic(cnic)
    if target is None:
        raise HTTPException(400, f"'{cnic}' does not look like a valid CNIC.")

    df = _get_cleaned_df(data_type, file_id, ip_name)

    cnic_col = _find_cnic_column(df)
    if cnic_col is None:
        raise HTTPException(422, f"No CNIC-like column found in cleaned file for '{file_id}'.")

    normalized = df[cnic_col].map(_normalize_cnic)
    mask = normalized == target

    if not mask.any():
        raise HTTPException(
            404,
            f"No records found with CNIC '{cnic}' in '{ip_name or file_id}'.",
        )

    subset = df[mask].where(pd.notna(df[mask]), None)
    records = [
        {"ip_name": ip_name or file_id, **record}
        for record in subset.to_dict(orient="records")
    ]

    return JSONResponse({
        "data_type": data_type.lower(),
        "ip_name": ip_name,
        "file_id": file_id,
        "cnic": target,
        "duplicate_count": len(records),
        "records": records,
    })


