"""
routes_report.py
────────────────
Cursor-paginated HTTP access to a *_report.parquet file, addressed by the
same (data_type, ip_name, file_id) layout used for storage:

    GET /api/report/{data_type}/{ip_name}/{file_id}/page   (beneficiary / banks / financials)
    GET /api/report/{data_type}/{file_id}/page             (certificates — no ip_name)

    ?page_size=20&cursor=<token>&raw=false

Pagination contract
-------------------
- First page: omit `cursor`.
- Each response carries pagination.next_cursor.
- Fetch the next page by passing that token back as `cursor`.
- next_cursor == null  →  last page reached.
The cursor is opaque; clients echo next_cursor back unchanged, never parse it.
- Alternatively, pass `page=<n>` (1-based) to jump directly to any page —
  forward, backward, or anywhere in between — without walking through
  cursors. `page` wins if both `page` and `cursor` are given.

Duplicates endpoint
--------------------
    GET /api/report/{data_type}/{ip_name}/{file_id}/duplicates
    GET /api/report/{data_type}/{file_id}/duplicates          (certificates)

Returns the *entire* `_duplicates.parquet` file as one JSON payload — no
pagination, no cursor. This file is a raw row-subset of the cleaned dataset
(rows flagged as UUID-duplicate OR CNIC-duplicate), so it carries whatever
columns the original data had — it has NO `is_dup_cnic` flag and no
dedicated CNIC column of its own. It's diagnostic data, not a substitute for
browsing the full report.

Duplicate-CNIC summary and data
---------------------------------
Previously this was read from one hardcoded, global JSON file that had to be
regenerated by hand any time an IP's data changed.

It is now computed live from every IP's own `{ip_name}_report.parquet`
under the requested data_type (discovered via iter_all_outputs) — every
row, not a pre-filtered subset — since only scanning the full population
lets us catch a CNIC that appears once in one IP and once in another (a
genuine cross-IP duplicate that no single IP's own per-file processing
could ever see on its own). The actual CNIC value is pulled out of each
row's `validation_status` per-filter detail, by matching any filter whose
`col` name contains "cnic" (case-insensitively — e.g. "DA_CNIC" — so this
isn't hardcoded to one column name), then normalized (whitespace, float
".0" artifacts, and non-digit separators stripped) so the same real CNIC
compares equal across IPs regardless of formatting differences.

The response shapes are deliberately kept separate:
  - `/page` attaches `duplicate_cnic_summary`  — rolled-up totals only.
  - `/duplicates` attaches `data` — a flat per-CNIC breakdown (cnic,
    duplicate_count, duplicate_in_no_of_ips, ip_names, ip_names_text), with
    NO aggregate summary block; that belongs solely to `/page`.
  - `/duplicates/cnic/records`, `/duplicates/cnic/occurrences`,
    `/duplicates/cnic/single-ip`, `/duplicates/cnic/cross-ip` — new,
    paginated drill-downs. Each backs exactly one number in
    duplicate_cnic_summary, so you can page through the actual records
    behind that count instead of just seeing the total:
        total_duplicate_cnic_records          -> /duplicates/cnic/records
        total_duplicate_occurrences           -> /duplicates/cnic/occurrences
        cnics_duplicated_in_single_ip         -> /duplicates/cnic/single-ip
        cnics_duplicated_across_multiple_ips  -> /duplicates/cnic/cross-ip
    All four use the exact same page/cursor/page_size pagination contract
    as `/page` (see paginate_list in report/pagination.py), including
    direct page-number jumps.
All are built from one shared, cached pool computation
(`_compute_duplicate_cnic_pool`) so the underlying report scan only runs
once per data_type per cache cycle, not once per endpoint.

Results are cached in-process, keyed by the (path, mtime) signature of
every report file that contributed — the cache rebuilds automatically the
moment any one of those files is rewritten, added, or removed.

Performance
-----------
Each parquet is loaded once, then cached in-process keyed by (path, mtime).
Repeated requests for an unchanged file are served from memory. If the file
is rewritten, its mtime changes and the cache rebuilds. Report pages and
duplicates dumps use separate caches since they're different files with
different access patterns (report is sorted once, duplicates is a raw dump).
The occurrence-records drill-down (full row per duplicate CNIC occurrence)
has its own cache too, since it's a second, heavier scan of every IP's
_cleaned.parquet beyond what the summary pool alone needs — it's only ever
computed if that specific endpoint is actually called.
"""
